// только если подписан ОДНИМ из них: подпись проверяет код, который уже стоит у человека, поэтому
// ключ едет внутри пакета, а не рядом с манифестом — с того же адреса его подменили бы вместе.
//
// Формат строки: `id` — первые 8 hex sha256 от сырого публичного ключа (32 байта Ed25519),
// `publicKey` — сырой ключ в base64 (как печатает scripts/release-keygen.mjs) или SPKI (PEM / base64 DER).
// `id` сверяется с ключом при каждой проверке: опечатка в этом файле — отказ, а не тихое «доверяю всем».
//
// РОТАЦИЯ: новый ключ дописывается сюда и выходит в релизе, подписанном СТАРЫМ; следующий релиз
// подписывается новым; старый убирается, когда версий без нового ключа у людей не осталось.
// Скомпрометированный ключ убирается сразу — тем же порядком, но без ожидания.
//
// Ключ владельца заведён 19.10.2026 через release-keygen.mjs; закрытая половина — только у владельца
// (менеджер паролей). Ротация — порядком выше.

